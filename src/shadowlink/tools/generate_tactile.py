"""Regenerate the fingertip touch sites from the collision meshes.

The tactile layout is sampled once, offline: for every finger we cast a 6x4
grid of rays through the distal collision geometry, then project each hit onto
the convex hull so visual concavities cannot hide a taxel.  The resulting
``*_sites.xml`` and ``sensors.xml`` are checked into the repository; the
simulator only reads those files.

Run this after changing fingertip geometry::

    shadowlink generate-tactile            # rewrite the package assets
    shadowlink generate-tactile --check    # fail if checked-in XML is stale
"""

from __future__ import annotations

import argparse
from collections.abc import Mapping
from pathlib import Path

import mujoco
import numpy as np

from shadowlink.paths import TACTILE_DIR

FINGERS = ("ff", "mf", "rf", "lf", "th")
ROWS = 6
COLS = 4


def _format_vector(vector: np.ndarray) -> str:
    return " ".join(f"{value:.9f}" for value in vector)


def _sample_finger(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    finger: str,
    probe_id: int,
) -> list[tuple[int, int, np.ndarray, np.ndarray]]:
    """Return body-local positions and outward normals, in row/column order."""
    body_id = model.body(f"rh_{finger}distal").id
    geom_ids = [
        index
        for index in range(model.ngeom)
        if model.geom_bodyid[index] == body_id
        and (model.geom_contype[index] or model.geom_conaffinity[index])
    ]
    if len(geom_ids) != 1:
        raise ValueError(f"{finger}: expected one fingertip collision geom, found {len(geom_ids)}")
    geom_id = geom_ids[0]

    model.geom_group[:] = 5
    model.geom_group[geom_id] = 3
    groups = np.array([0, 0, 0, 1, 0, 0], dtype=np.uint8)

    rotation = data.xmat[body_id].reshape(3, 3).copy()
    body_pos = data.xpos[body_id].copy()
    probe_mocap = model.body_mocapid[model.geom_bodyid[probe_id]]

    thumb = finger == "th"
    heights = np.linspace(0.011, 0.032, ROWS) if thumb else np.linspace(0.010, 0.029, ROWS)
    widths_mm = [7.5, 7.5, 7.0, 6.5, 5.0, 3.0] if thumb else [6.0, 6.0, 6.0, 6.0, 5.0, 3.0]
    widths = np.asarray(widths_mm) * 0.001

    samples: list[tuple[int, int, np.ndarray, np.ndarray]] = []
    for row, (height, width) in enumerate(zip(heights, widths, strict=True)):
        for col, x in enumerate(np.linspace(-width, width, COLS)):
            origin = body_pos + rotation @ np.array([x, -0.025, height])
            direction = rotation @ np.array([0.0, 1.0, 0.0])
            hit = np.array([-1], dtype=np.int32)
            normal = np.zeros(3)
            distance = mujoco.mj_ray(model, data, origin, direction, groups, True, -1, hit, normal)
            if distance < 0 or hit[0] != geom_id:
                raise ValueError(f"{finger}[{row},{col}]: ray missed the fingertip")
            mesh_point = origin + distance * direction

            # Ray queries hit mesh triangles.  Project onto the actual convex
            # collision hull too, so visual concavities cannot hide a taxel.
            data.mocap_pos[probe_mocap] = mesh_point + 0.004 * normal
            mujoco.mj_forward(model, data)
            segment = np.zeros(6)
            gap = mujoco.mj_geomDistance(model, data, geom_id, probe_id, 0.1, segment)
            if not 0 < gap < 0.01:
                raise ValueError(f"{finger}[{row},{col}]: invalid hull projection")
            normal = segment[3:] - segment[:3]
            normal /= np.linalg.norm(normal)
            if np.linalg.norm(segment[:3] - mesh_point) > 0.001:
                raise ValueError(f"{finger}[{row},{col}]: mesh/hull mismatch > 1 mm")
            samples.append(
                (
                    row,
                    col,
                    rotation.T @ (segment[:3] - body_pos),
                    rotation.T @ normal,
                )
            )
    return samples


def _site_lines(
    finger: str,
    samples: list[tuple[int, int, np.ndarray, np.ndarray]],
) -> list[str]:
    lines = [
        "<mujocoinclude>",
        "  <!-- Generated by generate_tactile.py; local z follows the collision normal. -->",
    ]
    positions = {(row, col): position for row, col, position, _ in samples}
    for row, col, position, normal in samples:
        # Project the body x axis into the tangent plane, keeping a stable
        # orientation for the other two axes of each flattened ellipsoid.
        tangent = np.array([1.0, 0.0, 0.0])
        tangent -= normal * np.dot(tangent, normal)
        tangent /= np.linalg.norm(tangent)
        frame = np.column_stack((tangent, np.cross(normal, tangent), normal))
        size = np.array([0.0022, 0.0023, 0.0013] if finger == "th" else [0.0018, 0.0019, 0.0012])
        # Taper the lateral radius where four columns approach each other at
        # the tip.  Keep a small gap rather than count one contact twice.
        for axis, neighbors in enumerate(
            (
                ((row, col - 1), (row, col + 1)),
                ((row - 1, col), (row + 1, col)),
            )
        ):
            spacings = [
                abs(np.dot(positions[key] - position, frame[:, axis]))
                for key in neighbors
                if key in positions
            ]
            if spacings:
                size[axis] = min(size[axis], 0.45 * min(spacings))
        quat = np.zeros(4)
        mujoco.mju_mat2Quat(quat, frame.ravel())
        name = f"{finger}_taxel_r{row}_c{col}"
        lines.append(
            f'  <site name="{name}" type="ellipsoid"'
            f' pos="{_format_vector(position)}" quat="{_format_vector(quat)}"'
            f' size="{_format_vector(size)}" group="4" rgba="0.15 0.65 1 0.65"/>'
        )
    lines.append("</mujocoinclude>")
    return lines


def generate(scene_xml: str | Path | None = None) -> dict[str, str]:
    """Generate every tactile XML file and return ``name -> content``."""
    if scene_xml is None:
        from shadowlink.paths import SCENE_XML

        scene_xml = SCENE_XML

    spec = mujoco.MjSpec.from_file(str(scene_xml))
    probe = spec.worldbody.add_body(name="tactile_sampling_probe", mocap=True)
    probe.add_geom(
        name="tactile_sampling_probe_geom",
        type=mujoco.mjtGeom.mjGEOM_SPHERE,
        size=[0.00001, 0, 0],
        contype=0,
        conaffinity=0,
    )
    model = spec.compile()
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    probe_id = model.geom("tactile_sampling_probe_geom").id

    files: dict[str, str] = {}
    sensors = [
        "<mujocoinclude>",
        "  <!-- Generated by generate_tactile.py; row 0 is nearest the joint. -->",
    ]
    for finger in FINGERS:
        samples = _sample_finger(model, data, finger, probe_id)
        files[f"{finger}_sites.xml"] = "\n".join(_site_lines(finger, samples)) + "\n"
        sensors.extend(
            f'  <touch name="touch_{finger}_taxel_r{row}_c{col}" '
            f'site="{finger}_taxel_r{row}_c{col}"/>'
            for row, col, _, _ in samples
        )
    sensors.append("</mujocoinclude>")
    files["sensors.xml"] = "\n".join(sensors) + "\n"
    return files


def _write_if_changed(path: Path, content: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def check_output(files: Mapping[str, str], out_dir: str | Path) -> list[str]:
    """Return the names of files that are missing or differ from ``files``."""
    directory = Path(out_dir)
    stale = []
    for name, content in files.items():
        path = directory / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(name)
    return stale


def main(out: str | Path | None = None, check: bool = False) -> int:
    out_dir = Path(out) if out is not None else TACTILE_DIR
    files = generate()

    if check:
        stale = check_output(files, out_dir)
        if stale:
            print(f"tactile XML is stale in {out_dir}: {', '.join(stale)}")
            print("run `shadowlink generate-tactile` to update it")
            return 1
        print(f"tactile XML is up to date ({len(files)} files, {len(FINGERS) * ROWS * COLS} sites)")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    changed = [
        name for name, content in files.items() if _write_if_changed(out_dir / name, content)
    ]
    if changed:
        print(f"updated {', '.join(changed)} in {out_dir}")
    else:
        print(f"tactile XML already up to date in {out_dir}")
    print(f"{len(FINGERS)} fingers x {ROWS} x {COLS} = {len(FINGERS) * ROWS * COLS} touch sites")
    return 0


def cli(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=None, help="output directory (default: package assets)")
    parser.add_argument("--check", action="store_true", help="fail if the checked-in XML differs")
    args = parser.parse_args(argv)
    return main(out=args.out, check=args.check)


__all__ = ["FINGERS", "ROWS", "COLS", "check_output", "cli", "generate", "main"]
